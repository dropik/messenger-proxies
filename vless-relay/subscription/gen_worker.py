#!/usr/bin/env python3
"""Generate a Cloudflare Worker that serves one subscription per relay user group.

Reads the relay's config.json, builds a vless:// link for every client listed in
subs.json, and writes worker.js with those links behind random tokens. Tokens are
kept in subs.json, so regenerating after a config change keeps the same URLs.

Usage (in vless-relay/):
    python3 subscription/gen_worker.py --address RELAY_IP     # first run creates subs.json
    python3 subscription/gen_worker.py                        # later runs reuse it

Then paste subscription/worker.js into the Worker editor and deploy.
subs.json and worker.js contain secrets and are gitignored.
"""
import argparse
import json
import os
import re
import secrets
import subprocess
import sys
from urllib.parse import urlencode, quote

HERE = os.path.dirname(os.path.abspath(__file__))
RELAY_DIR = os.path.dirname(HERE)
SUBS = os.path.join(HERE, "subs.json")
WORKER = os.path.join(HERE, "worker.js")


def load_config():
    text = open(os.path.join(RELAY_DIR, "config.json")).read()
    text = "\n".join(l for l in text.splitlines() if not re.match(r"^\s*//", l))
    return json.loads(text)


def public_key(private_key, container):
    out = subprocess.run(["docker", "exec", container, "xray", "x25519", "-i", private_key],
                         capture_output=True, text=True, check=True).stdout
    m = re.search(r"(?:Public key|PublicKey|Password)[^:]*:\s*(\S+)", out)
    if not m:
        sys.exit("could not derive the REALITY public key")
    return m.group(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--address", help="relay IP or hostname clients connect to (first run)")
    ap.add_argument("--container", default="vless-relay")
    args = ap.parse_args()

    c = load_config()
    inbound = next(i for i in c["inbounds"] if i["streamSettings"].get("security") == "reality")
    ss = inbound["streamSettings"]
    rs, xs = ss["realitySettings"], ss["xhttpSettings"]
    clients = {cl["email"]: cl["id"] for cl in inbound["settings"]["clients"]}

    if os.path.exists(SUBS):
        subs = json.load(open(SUBS))
    else:
        if not args.address:
            sys.exit("first run: pass --address RELAY_IP")
        subs = {"address": args.address, "update_hours": 12, "groups": {
            email: {"title": "Relay", "token": secrets.token_urlsafe(24)} for email in clients}}
    if args.address:
        subs["address"] = args.address

    pbk = public_key(rs["privateKey"], args.container)
    routes = {}
    for email, g in subs["groups"].items():
        if email not in clients:
            print(f"skip {email}: not a client in config.json")
            continue
        q = urlencode({
            "encryption": "none", "security": "reality", "sni": rs["serverNames"][0],
            "fp": "chrome", "pbk": pbk, "sid": rs["shortIds"][0], "type": "xhttp",
            "path": xs["path"], "host": xs.get("host", ""), "mode": xs.get("mode", "auto"),
        })
        link = f"vless://{clients[email]}@{subs['address']}:{inbound['port']}?{q}#{quote(g['title'])}"
        routes[g["token"]] = {"title": g["title"], "links": [link]}

    old = os.umask(0o077)
    json.dump(subs, open(SUBS, "w"), indent=2)
    with open(WORKER, "w") as f:
        f.write(WORKER_TEMPLATE.replace("__ROUTES__", json.dumps(routes, indent=2))
                               .replace("__HOURS__", str(subs["update_hours"])))
    os.umask(old)
    print(f"wrote {WORKER} with {len(routes)} subscription(s)")
    for email, g in subs["groups"].items():
        print(f"  {email}: https://<your-worker>.workers.dev/{g['token']}")


WORKER_TEMPLATE = r"""// Generated by gen_worker.py. Contains secrets: do not commit or share.
const SUBS = __ROUTES__;

export default {
  async fetch(request) {
    const token = new URL(request.url).pathname.slice(1);
    const sub = request.method === "GET" && Object.hasOwn(SUBS, token) ? SUBS[token] : null;
    if (!sub) return new Response("Not Found", { status: 404 });
    return new Response(btoa(sub.links.join("\n")), {
      headers: {
        "content-type": "text/plain; charset=utf-8",
        "cache-control": "no-store",
        "profile-title": "base64:" + btoa(sub.title),
        "profile-update-interval": "__HOURS__",
      },
    });
  },
};
"""

if __name__ == "__main__":
    main()
